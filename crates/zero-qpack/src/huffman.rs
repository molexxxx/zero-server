//! The static Huffman code of RFC 7541 Appendix B, which QPACK string literals
//! use "without modification" (RFC 9204 Section 4.1.2).
//!
//! The encoded data is "the bitwise concatenation of the codes corresponding to
//! each octet of the string literal", padded to an octet boundary with "the most
//! significant bits of the code corresponding to the EOS (end-of-string) symbol"
//! (RFC 7541 Section 5.2). The decoder enforces the three rules of that section:
//!
//! - "A padding strictly longer than 7 bits MUST be treated as a decoding error."
//! - "A padding not corresponding to the most significant bits of the code for
//!   the EOS symbol MUST be treated as a decoding error."
//! - "A Huffman-encoded string literal containing the EOS symbol MUST be treated
//!   as a decoding error."
//!
//! The code is canonical: the codes of each length form one contiguous range,
//! so the decoder reads one bit at a time and checks the code against the range
//! of its length. [`CODES`] is written into this file by a script from the
//! extracted Appendix B table; the four tables derived from it are generated by
//! the same script and rebuilt from [`CODES`] by a unit test.
//!
//! @see <https://www.rfc-editor.org/rfc/rfc7541.html#section-5.2>
//! @see <https://www.rfc-editor.org/rfc/rfc7541.html#appendix-B>

