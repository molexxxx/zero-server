/// Why a Huffman string was refused (RFC 7541 Section 5.2).
///
/// @see <https://www.rfc-editor.org/rfc/rfc7541.html#section-5.2>
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum HuffmanError {
    /// More than 7 bits of padding.
    Padding,
    /// Padding that is not the most significant bits of EOS.
    PaddingNotEos,
    /// The EOS symbol inside the data.
    Eos,
    /// The output slice is too short (slice API only).
    OutputFull,
}

impl HuffmanError {
    /// The name used in conformance vectors.
    ///
    /// # Returns
    ///
    /// `"padding"`, `"paddingNotEos"`, `"eos"` or `"outputFull"`.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Padding => "padding",
            Self::PaddingNotEos => "paddingNotEos",
            Self::Eos => "eos",
            Self::OutputFull => "outputFull",
        }
    }
}

/// The entry of `table` at `index`, read without indexing.
fn at<T: Copy>(table: &[T], index: u32) -> Option<T> {
    table.get(usize::try_from(index).ok()?).copied()
}

/// The most octets `encoded_len` Huffman octets can decode to.
///
/// That is floor(8n / 5), since the shortest code is 5 bits, computed as
/// 8 * (n / 5) + floor(8 * (n % 5) / 5) with saturating operations: exact for
/// every slice length, and `usize::MAX` for a larger argument, which no slice
/// has.
///
/// # Arguments
///
/// * `encoded_len` - the length of the Huffman-encoded data.
///
/// # Returns
///
/// The bound in octets.
#[must_use]
pub const fn decoded_len_bound(encoded_len: usize) -> usize {
    let whole = match encoded_len.checked_div(5) {
        Some(whole) => whole,
        None => 0,
    };
    let part = match encoded_len.checked_rem(5) {
        Some(part) => part,
        None => 0,
    };
    let tail = match part.saturating_mul(8).checked_div(5) {
        Some(tail) => tail,
        None => 0,
    };
    whole.saturating_mul(8).saturating_add(tail)
}

/// The octets [`encode`] writes for `input`.
///
/// The bit count is summed in `u64`, so a 32-bit target never overflows.
///
/// # Arguments
///
/// * `input` - the octets to encode.
///
/// # Returns
///
/// ceil(sum of the code lengths / 8).
#[must_use]
pub fn encoded_len(input: &[u8]) -> u64 {
    let bits = input.iter().fold(0u64, |bits, &octet| {
        let (_, len) = CODES.get(usize::from(octet)).copied().unwrap_or((0, 0));
        bits.saturating_add(u64::from(len))
    });
    bits.saturating_add(7).checked_shr(3).unwrap_or(0)
}

/// Appends the Huffman encoding of `input` to `out`, padded to an octet
/// boundary with the most significant bits of EOS (all ones).
///
/// @see <https://www.rfc-editor.org/rfc/rfc7541.html#section-5.2>
///
/// # Arguments
///
/// * `input` - the octets to encode.
/// * `out` - the buffer the encoding is appended to.
pub fn encode(input: &[u8], out: &mut Vec<u8>) {
    out.reserve(usize::try_from(encoded_len(input)).unwrap_or(0));
    let mut pending = 0u64;
    let mut bits = 0u32;
    for &octet in input {
        let (code, len) = CODES.get(usize::from(octet)).copied().unwrap_or((0, 0));
        let len = u32::from(len);
        pending = pending.checked_shl(len).unwrap_or(0) | u64::from(code);
        bits = bits.saturating_add(len);
        while bits >= 8 {
            bits = bits.saturating_sub(8);
            let [low, ..] = pending.checked_shr(bits).unwrap_or(0).to_le_bytes();
            out.push(low);
        }
        pending &= 1u64.checked_shl(bits).unwrap_or(0).wrapping_sub(1);
    }
    if bits > 0 {
        let pad = 8u32.saturating_sub(bits);
        let ones = 1u64.checked_shl(pad).unwrap_or(0).wrapping_sub(1);
        let [low, ..] = (pending.checked_shl(pad).unwrap_or(0) | ones).to_le_bytes();
        out.push(low);
    }
}

/// Decodes `input` and hands each decoded octet to `emit`.
fn decode_with(
    input: &[u8],
    mut emit: impl FnMut(u8) -> Result<(), HuffmanError>,
) -> Result<(), HuffmanError> {
    let mut code = 0u32;
    let mut len = 0u32;
    for &octet in input {
        for shift in (0..8u32).rev() {
            let bit = u32::from(octet.checked_shr(shift).unwrap_or(0) & 1);
            code = code.checked_shl(1).unwrap_or(0) | bit;
            len = len.saturating_add(1);
            let first = at(&FIRST, len).unwrap_or(0);
            let count = at(&COUNT, len).unwrap_or(0);
            match code.checked_sub(first) {
                Some(offset) if offset < count => {
                    let position = at(&INDEX, len).unwrap_or(0).saturating_add(offset);
                    let symbol = at(&SYMBOLS, position).unwrap_or(EOS);
                    let octet = u8::try_from(symbol).map_err(|_| HuffmanError::Eos)?;
                    emit(octet)?;
                    code = 0;
                    len = 0;
                }
                _ if len >= MAX_CODE_LEN => return Err(HuffmanError::Padding),
                _ => {}
            }
        }
    }
    if len > 7 {
        return Err(HuffmanError::Padding);
    }
    if code.count_ones() != len {
        return Err(HuffmanError::PaddingNotEos);
    }
    Ok(())
}

/// Decodes `input` into `out`.
///
/// @see <https://www.rfc-editor.org/rfc/rfc7541.html#section-5.2>
///
/// # Arguments
///
/// * `input` - the Huffman-encoded data.
/// * `out` - receives the decoded octets from its start.
///
/// # Returns
///
/// The octets written.
///
/// # Errors
///
/// [`HuffmanError::Padding`], [`HuffmanError::PaddingNotEos`] and
/// [`HuffmanError::Eos`] for the RFC 7541 Section 5.2 rules, and
/// [`HuffmanError::OutputFull`] when `out` is too short.
pub fn decode(input: &[u8], out: &mut [u8]) -> Result<usize, HuffmanError> {
    let mut slots = out.iter_mut();
    let mut written = 0usize;
    decode_with(input, |octet| {
        let slot = slots.next().ok_or(HuffmanError::OutputFull)?;
        *slot = octet;
        written = written.saturating_add(1);
        Ok(())
    })?;
    Ok(written)
}

/// Decodes `input`, appending to `out` after reserving
/// [`decoded_len_bound`]`(input.len())` octets.
///
/// @see <https://www.rfc-editor.org/rfc/rfc7541.html#section-5.2>
///
/// # Arguments
///
/// * `input` - the Huffman-encoded data.
/// * `out` - the buffer the decoded octets are appended to; on an error it holds
///   the octets decoded before the fault.
///
/// # Errors
///
/// [`HuffmanError::Padding`], [`HuffmanError::PaddingNotEos`] and
/// [`HuffmanError::Eos`]; never [`HuffmanError::OutputFull`].
pub fn decode_to_vec(input: &[u8], out: &mut Vec<u8>) -> Result<(), HuffmanError> {
    out.reserve(decoded_len_bound(input.len()));
    decode_with(input, |octet| {
        out.push(octet);
        Ok(())
    })
}

